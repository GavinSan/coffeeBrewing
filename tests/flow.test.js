const BASE = process.env.BASE || BASE;
const { chromium, devices } = require('playwright');
const OUT = require('path').join(__dirname, '..', 'test-results') + '/';
require('fs').mkdirSync(OUT, { recursive: true });
let fails = 0;
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'], serviceWorkers: 'block' });
  await ctx.route('**/config.js', (r) => r.fulfill({ contentType: 'text/javascript', body: "window.COFFEE_CLOUD={url:'https://x.supabase.co',key:''};" }));
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  await p.clock.install({ time: new Date('2026-11-18T08:00:00') });
  await p.goto(BASE);
  await p.clock.runFor(100);
  ok(p.url().endsWith('#setup'), 'new user: starts at gear setup');
  await p.click('[data-a=setupDone]'); await p.clock.runFor(100);
  const shot = (n) => p.screenshot({ path: OUT + n + '.png', fullPage: true });
  const txt = (s) => p.textContent(s);
  // Under the fake clock a hash change renders only when the clock moves: tick until the condition holds (max 2 s)
  const settle = async (cond) => { for (let i = 0; i < 40; i++) { if (await cond()) return true; await p.clock.runFor(50); } return cond(); };

  // 1. new user lands on Brew with a clear first step
  ok(await settle(async () => (await p.locator('text=Start with a bag of beans').count()) === 1), 'new user: home asks for a bag');
  await shot('01-home-empty');
  await p.click('.welcome [data-a=newBean]');
  ok(await p.locator('text=Rating').count() === 0, 'form: no bean rating');
  await p.fill('#f-name', 'Guji Hambela');
  await p.fill('#f-roaster', 'Onyx');
  await p.type('#f-price', '2a4.5.0');
  ok(await p.inputValue('#f-price') === '24.50', 'price keeps digits and one point: ' + await p.inputValue('#f-price'));
  await p.type('#f-weight', '250g');
  ok(await p.inputValue('#f-weight') === '250', 'weight digits only: ' + await p.inputValue('#f-weight'));
  ok((await txt('#perg')).includes('$0.10 per gram'), 'cost per gram updates');
  await p.focus('#f-origin'); await p.keyboard.type('Eth');
  ok(await p.locator('#sg-origin [data-v=Ethiopia]').count() === 1, 'origin suggests Ethiopia');
  await p.click('#sg-origin [data-v=Ethiopia]');
  ok(await p.inputValue('#f-origin') === 'Ethiopia', 'origin suggestion fills');
  await p.click('[data-a=setB][data-v="Carbonic maceration"]');
  await p.locator('#f-roast').fill('2');
  ok((await txt('#roast-lbl')) === 'Medium-light', 'roast slider label');
  await p.click('#flv-groups [data-v=Peach]');
  await p.fill('#f-flv', 'jasm');
  ok(await p.locator('#flv-groups [data-v]').count() === 1, 'flavour search filters to Jasmine');
  await p.click('#flv-groups [data-v=Jasmine]');
  await p.fill('#f-flv', 'lychee'); await p.press('#f-flv', 'Enter');
  ok((await txt('#flv-picked')).replace(/\s+/g, ' ').includes('Lychee'), 'custom flavour added');
  await shot('02-form');
  await p.click('[data-a=saveBean]');
  await p.clock.runFor(900);
  const card = await p.locator('#fall .addcard').boundingBox(), vh = 844;
  ok(card && card.y > 0 && card.y + card.height < vh, 'added card fully on screen');
  ok(await p.locator('#fall .pile i').count() <= 50, 'light animation: ' + await p.locator('#fall .pile i').count() + ' beans');
  await shot('03-added');
  await p.click('[data-a=addedBrew]');
  ok(p.url().endsWith('#method'), 'first brew goes to method');
  await shot('04-method');
  await p.click('[data-a=toRecipe]');
  await shot('05-recipe');
  await p.click('[data-a=toTimer]');
  await p.click('#t-main');
  await p.clock.runFor(3000 + 6500);  // countdown + 6.5 s into the first pour
  const g1 = parseInt(await txt('#t-gnow'));
  ok(g1 > 25 && g1 < 40, 'water ramps during pour 1 (6.5 s): ' + g1 + ' g, ' + await txt('#t-act'));
  await shot('06-timer-pour');
  await p.clock.runFor(10000);
  ok(parseInt(await txt('#t-gnow')) === 64 && /drain/i.test(await txt('#t-act')) && /next: Pour 2 in/.test(await txt('#t-gto')), 'after pour: holds at 64 g, waits for pour 2 — ' + await txt('#t-gto'));
  await shot('07-timer-wait');
  await p.clock.runFor(30000);
  const g2 = parseInt(await txt('#t-gnow'));
  ok(g2 > 64 && g2 < 128, 'pour 2 ramps from 64: ' + g2);
  await p.click('[data-a=tDone]'); await p.waitForURL(/#brew$/);
  ok(await settle(async () => (await p.locator('.banner').count()) === 1), 'done: home with rate prompt');
  await p.click('.banner [data-a=rate]');
  await p.click('[data-a=rateQ][data-n="4"]'); await p.click('[data-a=adjust][data-v=Finer]');
  await p.click('[data-a=saveRate]');
  ok(/grind finer/.test(await txt('.hero')), 'home hero reminds: grind finer');
  await shot('08-home-hero');
  await p.click('.hero [data-a=startBrew]');
  ok(p.url().endsWith('#recipe'), 'second brew skips straight to recipe');
  await p.click('[data-a=applyAdj]');
  ok(await p.locator('[data-a=applyAdj]').count() === 0, 'apply hint consumed');

  await p.clock.resume();
  // 2. load a realistic shelf and check the library + journal
  await p.evaluate(() => {
    const roasters = ['Onyx', 'Sey', 'Tim Wendelboe', 'Prodigal', 'Luminous'], origins = ['Ethiopia', 'Kenya', 'Colombia', 'Panama', 'Rwanda'];
    const procs = ['Washed', 'Natural', 'Honey', 'Anaerobic'];
    const now = Date.now(), day = 864e5, d = (ms) => new Date(ms).toISOString().slice(0, 10);
    const st = { beans: [], brews: [], grinders: [{ id: 'g1', name: 'Comandante C40', burr: 'Conical', setting: '24', step: 1 }], owned: ['v60', 'orea', 'switch'], recipes: [], filters: [], flavors: [], processes: [], countdown: 3, updatedAt: 1 };
    for (let i = 0; i < 14; i++) {
      const bought = now - (130 - i * 9) * day;
      const b = { id: 'b' + i, name: ['Guji', 'Nyeri AA', 'Huila', 'Geisha', 'Kivu', 'Sidama', 'Kirinyaga', 'Nariño', 'Boquete', 'Nyamasheke', 'Yirgacheffe', 'Embu', 'Cauca', 'Volcán'][i],
        roaster: roasters[i % 5], origin: origins[i % 5], process: procs[i % 4], roast: 1 + (i % 3), price: 18 + i, weight: 250, roastDate: d(bought - 6 * day), buyDate: d(bought), notes: ['Citrus', 'Floral'], openDate: d(bought) };
      if (i < 10) b.finishDate = d(bought + 12 * day);
      st.beans.unshift(b);
      for (let k = 0; k < 7; k++) { const at = bought + k * 1.6 * day + 8 * 3600e3; if (at > now) break; st.brews.push({ id: 'w' + i + k, beanId: b.id, at, date: d(at), method: k % 4 === 3 ? 'aero' : 'pour', dripper: ['v60', 'orea', 'switch'][k % 3], filter: 'Cafec Abaca', recipeId: k % 4 === 3 ? 'ap' : '46', dose: 15 + (k % 3), ratio: 16, temp: 93, grind: 24, grinderId: 'g1', elapsed: 200, stars: (i * 3 + k) % 6 === 0 ? 0 : 2 + ((i + k) % 4), ratedAt: 1, r: null, adjust: '' }); }
    }
    st.brews.sort((a, b) => a.at - b.at);
    localStorage.setItem('coffee-pwa-v1', JSON.stringify(st));
  });
  await p.goto(BASE + '#beans'); await p.reload();
  ok(await p.locator('#blist .row').count() === 4, 'beans: open tab shows 4 open bags');
  await p.click('[data-a=pref][data-k=beanTab][data-v=all]');
  ok(await p.locator('#blist .row').count() === 14, 'beans: all shows 14');
  await p.fill('#f-q', 'kenya');
  ok(await p.locator('#blist .row').count() === 3, 'search by origin: ' + await p.locator('#blist .row').count());
  await p.fill('#f-q', '');
  await p.selectOption('select[data-pref=sort]', 'rating');
  const firstStars = parseFloat(await p.locator('#blist .row .rt .fw').first().textContent());
  const allStars = await p.$$eval('#blist .row .rt .fw', (xs) => xs.map((x) => parseFloat(x.textContent)));
  ok(allStars.every((v, i) => i === 0 || allStars[i - 1] >= v), 'sorted by rating, top ' + firstStars);
  await p.click('[data-a=pref][data-k=min]');
  ok(allStars.filter((v) => v >= 4).length === await p.locator('#blist .row').count(), '4★+ filter');
  await p.click('[data-a=pref][data-k=min]');
  await p.click('[data-a=pref][data-k=group]');
  ok(await p.locator('#blist .label').count() === 5, 'grouped by 5 roasters');
  await shot('09-beans');
  await p.click('[data-a=pref][data-k=group]');
  await p.click('#blist .row >> nth=0'); await p.waitForSelector('text=Best cup');
  ok(/#bean\//.test(p.url()) && await p.locator('text=Best cup').count() === 1, 'bean detail with best cup');
  await shot('10-bean-detail');
  await p.goto(BASE + '#journal');
  ok(await p.locator('.stat').count() === 4 && await p.locator('.chart .bar').count() > 0, 'journal: KPIs and chart');
  await p.click('.chart rect.hit >> nth=-1');
  ok(/cup/.test(await txt('#chart-cap')), 'tap bar shows detail: ' + await txt('#chart-cap'));
  await p.click('[data-a=pref][data-k=by][data-v=roaster]');
  ok(await p.locator('.tbl .tr:not(.th)').count() >= 3, 'breakdown by roaster rows');
  await p.click('[data-a=pref][data-k=tsort][data-v=stars]');
  const rs = await p.$$eval('.tbl .tr:not(.th) .n:nth-child(3)', (xs) => xs.map((x) => parseFloat(x.textContent) || 0));
  ok(rs.every((v, i) => i === 0 || rs[i - 1] >= v), 'table sorts by rating');
  await p.selectOption('select[data-pref=lr]', '5');
  const st5 = await p.$$eval('.dayh + .list .row .fw.nowrap', (xs) => xs.map((x) => parseInt(x.textContent)));
  ok(st5.length > 0 && st5.every((v) => v === 5), 'log filter: only 5★ (' + st5.length + ')');
  await p.selectOption('select[data-pref=lr]', '');
  await p.click('[data-a=pref][data-k=period][data-v=all]');
  await shot('11-journal');

  // 3. repeat buys: suggestions + buy again
  await p.goto(BASE + '#beans'); await p.click('[data-a=newBean] >> nth=0'); await p.waitForSelector('h1:text("New bag")');
  ok(await p.locator('[data-a=copyBean]').count() > 0, 'new bag offers previous bags');
  await p.focus('#f-roaster');
  ok(await p.locator('#sg-roaster .chip').count() === 5, 'roaster suggestions on focus');
  await p.click('#sg-roaster [data-v=Sey]');
  ok(await p.inputValue('#f-roaster') === 'Sey' && await p.inputValue('#f-weight') === '250', 'roaster picked, weight filled from last bag');
  await p.click('[data-a=copyBean] >> nth=0');
  ok((await p.inputValue('#f-name')).length > 0 && await p.inputValue('#f-roastDate') === '' && /Copied from/.test(await txt('.hint')), 'copy prefills and clears roast date');
  await shot('12-copy');
  await p.goto(BASE + '#gear'); await shot('13-gear');
  ok(await p.locator('text=Sync').count() === 0 && await p.locator('text=Backup').count() === 0, 'gear has no account');
  await p.click('.ib.av'); await p.waitForSelector('h1:text("Account")');
  ok(p.url().endsWith('#account') && await p.locator('text=Backup').count() === 1, 'avatar opens account page');
  ok(errs.length === 0, 'no page errors ' + errs.join(' | '));
  await b.close();
  console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
  process.exit(fails ? 1 : 0);
})();
